/* USER CODE BEGIN 4 */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance != TIM3) return;  // TIM3 = 0.5 ms sampler
    if (!start_sending) return;

    SamplePacket pkt;

    // Header
    pkt.header[0] = 0x3C;
    pkt.header[1] = 0x3E;
    pkt.header[2] = 0x00;

    // Timestamp (µs)
    pkt.timestamp_us = __HAL_TIM_GET_COUNTER(&htim2);

    // Sequence
    pkt.seq = seq++;

    // Dummy channels (replace with your sensors)
    for (int i = 0; i < PACKET_SIZE; i++)
        pkt.ch[i] = i * 100;

    // Send packet
    HAL_UART_Transmit(&huart1, (uint8_t*)&pkt, sizeof(pkt), HAL_MAX_DELAY);
}

void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance != USART1)
        return;

    if (rx_byte != '\r' && rx_byte != '\n' && rx_index < sizeof(rx_buffer)-1)
    {
        rx_buffer[rx_index++] = rx_byte;
    }
    else
    {
        rx_buffer[rx_index] = '\0';

        if (strcmp(rx_buffer, "numx,all") == 0)
        {
            start_sending = 1;    // start streaming
            seq = 0;
        }
        else if (strcmp(rx_buffer, "stop") == 0)
        {
            start_sending = 0;    // stop streaming
        }

        rx_index = 0;
    }

    HAL_UART_Receive_IT(&huart1, &rx_byte, 1);

}
